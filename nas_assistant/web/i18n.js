function pickLanguage() {
  const wanted = [];
  try {
    const ha = JSON.parse(localStorage.getItem("selectedLanguage"));
    if (ha) wanted.push(ha);
  } catch { /* not inside Home Assistant */ }
  wanted.push(...(navigator.languages || [navigator.language]));
  for (const tag of wanted) {
    const base = String(tag).toLowerCase().split(/[-_]/)[0];
    if (MESSAGES[base]) return { lang: base, locale: tag };
  }
  return { lang: "en", locale: "en" };
}

const { lang: LANG, locale: LOCALE } = pickLanguage();
const plurals = new Intl.PluralRules(LOCALE);

function t(key, vars = {}) {
  let text = MESSAGES[LANG][key] ?? MESSAGES.en[key] ?? key;
  if (typeof text === "object") text = text[plurals.select(vars.n)] ?? text.other;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? vars[name] : m));
}

// Server messages are in English; show them in the UI language when we know them.
const tError = (message) => (MESSAGES[LANG].errors || {})[message] || message;

function translatePage() {
  document.documentElement.lang = LANG;
  document.querySelectorAll("[data-i18n]").forEach((node) => { node.textContent = t(node.dataset.i18n); });
  document.querySelectorAll("[data-i18n-title]").forEach((node) => { node.title = t(node.dataset.i18nTitle); });
}
